/**
 * The SVG filters behind `.glass-bar` and `.glass-pill`, mounted once in the
 * root layout.
 *
 * Liquid Glass is defined by LENSING — light bending at the edges — not by
 * blur. The pipeline: blur the backdrop a touch, bend it with a displacement
 * map, oversaturate that bent copy, mask it down to the rim with a specular
 * map, and screen it back over the bend.
 *
 * The displacement maps in /public/glass are neutral 128/128 through the
 * middle and ramp only inside a band at the border, so the distortion lands
 * at the rim and not across the face. A turbulence map instead gives the
 * wobbly-frosted look, which is a different and much worse effect. They are
 * generated by scripts/make-glass-maps.py — regenerate rather than hand-edit.
 *
 * Chromium only: Firefox and WebKit parse `backdrop-filter: url(...)` but
 * render the blur alone, which is a clean fallback (see app/globals.css).
 */
export default function GlassFilters() {
  return (
    <svg
      width={0}
      height={0}
      aria-hidden
      focusable="false"
      className="pointer-events-none absolute h-0 w-0 overflow-hidden"
    >
      <defs>
        <filter
          id="ngf-lens-bar"
          x="0%"
          y="0%"
          width="100%"
          height="100%"
          colorInterpolationFilters="sRGB"
        >
          <feGaussianBlur in="SourceGraphic" stdDeviation="1" result="soft" />
          <feImage
            href="/glass/bar-disp.png"
            x="0"
            y="0"
            width="100%"
            height="100%"
            preserveAspectRatio="none"
            result="map"
          />
          <feDisplacementMap
            in="soft"
            in2="map"
            scale="44"
            xChannelSelector="R"
            yChannelSelector="G"
            result="warp"
          />
          <feColorMatrix in="warp" type="saturate" values="7" result="warpsat" />
          <feImage
            href="/glass/bar-spec.png"
            x="0"
            y="0"
            width="100%"
            height="100%"
            preserveAspectRatio="none"
            result="rim"
          />
          <feComposite in="warpsat" in2="rim" operator="in" result="rimlit" />
          <feBlend in="rimlit" in2="warp" mode="screen" />
        </filter>

        <filter
          id="ngf-lens-pill"
          x="0%"
          y="0%"
          width="100%"
          height="100%"
          colorInterpolationFilters="sRGB"
        >
          <feGaussianBlur in="SourceGraphic" stdDeviation="1" result="soft" />
          <feImage
            href="/glass/pill-disp.png"
            x="0"
            y="0"
            width="100%"
            height="100%"
            preserveAspectRatio="none"
            result="map"
          />
          <feDisplacementMap
            in="soft"
            in2="map"
            scale="28"
            xChannelSelector="R"
            yChannelSelector="G"
            result="warp"
          />
          <feColorMatrix in="warp" type="saturate" values="7" result="warpsat" />
          <feImage
            href="/glass/pill-spec.png"
            x="0"
            y="0"
            width="100%"
            height="100%"
            preserveAspectRatio="none"
            result="rim"
          />
          <feComposite in="warpsat" in2="rim" operator="in" result="rimlit" />
          <feBlend in="rimlit" in2="warp" mode="screen" />
        </filter>
      </defs>
    </svg>
  )
}
